"""Generate the PCB06 click arrays from the preserved, unmodified source WAVs."""

from __future__ import annotations

import argparse
import hashlib
import struct
import wave
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parents[1]
ASSETS = FIRMWARE / "audio" / "button-clicks"
HEADER = FIRMWARE / "relay_client" / "pcb06_button_sounds.h"
SAMPLE_RATE = 24000
SOUNDS = (
    (
        "play-talk.wav",
        "kPlayTalk",
        912,
        "6555d963bd0eaf7d22a103fa491f19e6cc5977b4f91090085ab30d1e2555e5de",
    ),
    (
        "volume-tick.wav",
        "kVolumeTick",
        552,
        "28714b76350f3aadb7caa704d6d923ae23890ebb46f8dc2f21d3576599a8c63b",
    ),
)


def read_pcm(path: Path, frames: int, expected_sha256: str) -> bytes:
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected_sha256:
        raise ValueError(f"Original WAV hash mismatch: {path.name}")
    with wave.open(str(path), "rb") as source:
        if (
            source.getnchannels() != 1
            or source.getsampwidth() != 2
            or source.getframerate() != SAMPLE_RATE
            or source.getnframes() != frames
            or source.getcomptype() != "NONE"
        ):
            raise ValueError(f"Unexpected PCM format or length: {path.name}")
        pcm = source.readframes(frames)
    if len(pcm) != frames * 2:
        raise ValueError(f"Truncated PCM: {path.name}")
    return pcm


def render_header() -> str:
    lines = [
        "#pragma once",
        "",
        "// Generated by firmware/tools/generate_button_sounds.py. Do not hand-edit.",
        "// Exact source PCM; no resampling, gain adjustment, or heap allocation.",
        "// Provenance: firmware/audio/button-clicks/README.md.",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace pcb06_sounds {",
        f"inline constexpr uint32_t kSampleRate = {SAMPLE_RATE};",
        "",
    ]
    for filename, symbol, frames, expected_hash in SOUNDS:
        pcm = read_pcm(ASSETS / filename, frames, expected_hash)
        samples = struct.unpack(f"<{frames}h", pcm)
        lines.extend(
            (
                f"// {filename}: {frames} samples, {frames * 1000 // SAMPLE_RATE} ms.",
                f"// WAV SHA-256: {expected_hash}",
                f"// PCM SHA-256: {hashlib.sha256(pcm).hexdigest()}",
                f"inline constexpr int16_t {symbol}[] = {{",
            )
        )
        for start in range(0, frames, 12):
            lines.append(
                "  " + ", ".join(str(x) for x in samples[start : start + 12]) + ","
            )
        lines.extend(
            (
                "};",
                f"inline constexpr size_t {symbol}Samples = sizeof({symbol}) / sizeof({symbol}[0]);",
                "",
            )
        )
    lines.append("}  // namespace pcb06_sounds")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Check the header without writing"
    )
    args = parser.parse_args()
    generated = render_header()
    if args.check:
        if HEADER.read_text() != generated:
            parser.exit(1, "Button sound header is stale; regenerate it.\n")
        print("Button sound header matches the original WAVs.")
    else:
        HEADER.write_text(generated)
        print(f"Generated {HEADER}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
