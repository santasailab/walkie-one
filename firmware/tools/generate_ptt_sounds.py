"""Resample the preserved Squelch Gate WAVs and generate their static header."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import struct
import subprocess
import wave
from pathlib import Path

FIRMWARE = Path(__file__).resolve().parents[1]
ASSETS = FIRMWARE / "audio" / "ptt-sounds"
HEADER = FIRMWARE / "relay_client" / "pcb06_ptt_sounds.h"
RATE = 24000
FILTER = (
    "aresample=24000:resampler=swr:filter_size=32:phase_shift=10:"
    "linear_interp=0:exact_rational=1:dither_method=none"
)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def read_wav(data: bytes, rate: int) -> bytes:
    with wave.open(io.BytesIO(data), "rb") as source:
        if (
            source.getnchannels(),
            source.getsampwidth(),
            source.getframerate(),
            source.getcomptype(),
        ) != (1, 2, rate, "NONE"):
            raise ValueError(f"Expected mono PCM16 at {rate} Hz")
        frames = source.getnframes()
        pcm = source.readframes(frames)
    if len(pcm) != frames * 2:
        raise ValueError("Truncated WAV")
    return pcm


def wav_bytes(pcm: bytes) -> bytes:
    output = io.BytesIO()
    with wave.open(output, "wb") as target:
        target.setnchannels(1)
        target.setsampwidth(2)
        target.setframerate(RATE)
        target.writeframes(pcm)
    return output.getvalue()


def sources() -> list[dict]:
    records = json.loads((ASSETS / "provenance.json").read_text())["assets"]
    for record in records:
        data = (ASSETS / record["original"]).read_bytes()
        if digest(data) != record["sha256"]:
            raise ValueError("Original WAV changed: " + record["original"])
        pcm = read_wav(data, 44100)
        if len(pcm) != record["frames"] * 2 or digest(pcm) != record["pcm_sha256"]:
            raise ValueError("Original PCM changed: " + record["original"])
    return records


def resample(ffmpeg: str) -> tuple[list[dict], dict[str, bytes]]:
    records = sources()
    converted = {}
    for record in records:
        command = [
            ffmpeg,
            "-nostdin",
            "-hide_banner",
            "-loglevel",
            "error",
            "-i",
            str(ASSETS / record["original"]),
            "-map",
            "0:a:0",
            "-af",
            FILTER,
            "-ac",
            "1",
            "-ar",
            str(RATE),
            "-threads",
            "1",
            "-flags:a",
            "+bitexact",
            "-c:a",
            "pcm_s16le",
            "-f",
            "s16le",
            "pipe:1",
        ]
        pcm = subprocess.run(command, check=True, capture_output=True).stdout
        if not pcm or len(pcm) % 2:
            raise ValueError("FFmpeg returned invalid PCM")
        converted[record["symbol"]] = pcm
    return records, converted


def render_header(records: list[dict], converted: dict[str, bytes]) -> str:
    lines = [
        "#pragma once",
        "",
        "// Generated by firmware/tools/generate_ptt_sounds.py. Do not hand-edit.",
        "// Squelch Gate originals resampled 44.1 -> 24 kHz, without normalization.",
        "// Static flash data; runtime owns the continuous bed's one fade in/out.",
        "// Provenance: firmware/audio/ptt-sounds/README.md.",
        "#include <array>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "namespace pcb06_ptt_sounds {",
        f"inline constexpr uint32_t kSampleRate = {RATE};",
        "",
    ]
    for record in records:
        name = record["symbol"]
        pcm = converted[name]
        count = len(pcm) // 2
        samples = struct.unpack(f"<{count}h", pcm)
        lines.extend(
            (
                f"// PCM SHA-256: {digest(pcm)}",
                f"inline constexpr std::array<int16_t, {count}> {name} = {{",
            )
        )
        for start in range(0, count, 12):
            lines.append(
                "  " + ", ".join(str(x) for x in samples[start : start + 12]) + ","
            )
        lines.extend(
            ("};", f"inline constexpr size_t {name}Samples = {name}.size();", "")
        )
    lines.append("}  // namespace pcb06_ptt_sounds")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ffmpeg", default="ffmpeg")
    parser.add_argument(
        "--check", action="store_true", help="Reproduce and compare without writing"
    )
    args = parser.parse_args()
    records, converted = resample(args.ffmpeg)
    header = render_header(records, converted)
    if args.check:
        if HEADER.read_text() != header:
            parser.exit(1, "PTT header differs from deterministic conversion.\n")
        for record in records:
            destination = ASSETS / "pcm24k" / Path(record["original"]).name
            if destination.read_bytes() != wav_bytes(converted[record["symbol"]]):
                parser.exit(1, f"Converted WAV differs: {destination.name}\n")
        print("PTT header and WAVs reproduce exactly from the preserved originals.")
        return 0
    (ASSETS / "pcm24k").mkdir(exist_ok=True)
    info = {
        "ffmpeg_version": subprocess.run(
            [args.ffmpeg, "-version"], check=True, capture_output=True, text=True
        ).stdout.splitlines()[0],
        "filter": FILTER,
        "dither": "none",
        "normalization": "none",
        "sample_rate": RATE,
        "format": "mono PCM16 little-endian",
        "assets": [],
    }
    for record in records:
        pcm = converted[record["symbol"]]
        destination = ASSETS / "pcm24k" / Path(record["original"]).name
        data = wav_bytes(pcm)
        destination.write_bytes(data)
        samples = struct.unpack(f"<{len(pcm) // 2}h", pcm)
        info["assets"].append(
            {
                "symbol": record["symbol"],
                "path": str(destination.relative_to(ASSETS)),
                "frames": len(samples),
                "peak": max(abs(x) for x in samples),
                "wav_sha256": digest(data),
                "pcm_sha256": digest(pcm),
            }
        )
    HEADER.write_text(header)
    (ASSETS / "conversion.json").write_text(json.dumps(info, indent=2) + "\n")
    print(json.dumps(info, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
